"""Import TFDA open nutrition data; requires opencc-python-reimplemented only here.

Usage: python scripts/import-food-catalog.py <official CSV ZIP> <output .py>
Source: https://data.gov.tw/dataset/8543 (Open Government Data License 1.0).
The runtime uses the checked-in snapshot and never downloads nutrition data.
"""
import csv
import hashlib
import io
import math
from pathlib import Path
import re
import sys
import zipfile

from opencc import OpenCC


def read_foods(archive_path: Path):
    convert = OpenCC('t2s').convert
    records = {}
    with zipfile.ZipFile(archive_path) as archive:
        csv_names = [name for name in archive.namelist() if name.lower().endswith('.csv')]
        if len(csv_names) != 1:
            raise ValueError('Expected one official nutrition CSV')
        with archive.open(csv_names[0]) as source:
            for row in csv.DictReader(io.TextIOWrapper(source, encoding='utf-8-sig')):
                if row['分析項'] != '熱量' or row['含量單位'] != 'kcal':
                    continue
                raw_energy = row['每100克含量'].strip()
                if not raw_energy:
                    continue
                energy = float(raw_energy)
                if not math.isfinite(energy) or not 0 <= energy <= 1000:
                    raise ValueError('Invalid kcal/100g in ' + row['整合編號'])
                original = row['樣品名稱'].strip()
                aliases = {original}
                for alias in re.split('[,，、;；]', row['俗名']):
                    if alias.strip():
                        aliases.update((alias.strip(), convert(alias.strip())))
                name = convert(original)
                aliases.discard(name)
                record = (row['整合編號'], name, tuple(sorted(aliases)), convert(row['食品分類']),
                          energy, convert(row['內容物描述'].strip()))
                if record[0] in records:
                    raise ValueError('Duplicate food ID: ' + record[0])
                records[record[0]] = record
    if len(records) < 2000:
        raise ValueError('Incomplete source export')
    return sorted(records.values())


if __name__ == '__main__':
    source, output = map(Path, sys.argv[1:])
    records = read_foods(source)
    header = '''"""TFDA 2026 食品營養成分資料集 (2026-10-05 release).

Provider: 衛生福利部食品藥物管理署. Source: https://data.gov.tw/dataset/8543
Open Government Data License 1.0: https://data.gov.tw/license
Modified: retain kcal/100g records; simplified search names/aliases via OpenCC.
Values refer to edible weight and the stated sample preparation, not any recipe.
Generated by scripts/import-food-catalog.py; do not edit individual records here.
"""
SOURCE_URL = 'https://data.gov.tw/dataset/8543'
LICENSE_URL = 'https://data.gov.tw/license'
SOURCE_RELEASE = '2026-10-05'
IMPORTED_ON = '2026-11-04'
'''
    header += 'SOURCE_ZIP_SHA256 = ' + repr(hashlib.sha256(source.read_bytes()).hexdigest()) + '\n'
    header += '# ID, name, aliases, category, kcal/100g, sample description\nFOOD_DATA = (\n'
    output.write_text(header + ''.join('    ' + repr(row) + ',\n' for row in records) + ')\n', encoding='utf-8')
    print(f'Imported {len(records)} food energy records')
